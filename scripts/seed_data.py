def seed_listings(db=None) -> int:
    """Idempotent sync of verified genuine Indian internship opportunities.
    Inserts missing listings and updates existing ones with active open deadlines."""
    close_db = False
    if db is None:
        db = next(get_db())
        close_db = True

    try:
        now = datetime.now(timezone.utc).replace(tzinfo=None)
        listings = get_verified_listings(now)

        by_url = {i.apply_url_key: i for i in db.scalars(select(Internship)).all()}
        by_fp = {i.fingerprint: i for i in db.scalars(select(Internship)).all()}

        count_added = 0
        count_updated = 0

        for item in listings:
            fp = fingerprint(item["title"], item["company"], item["city"], item["work_type"])
            sb = skills_blob(item["skills"])

            existing = by_url.get(item["application_url"]) or by_fp.get(fp)

            if existing:
                # Update existing listing with fresh active deadline and verified status
                existing.title = item["title"]
                existing.company = item["company"]
                existing.company_website = item["company_website"]
                existing.description = item["description"]
                existing.skills = item["skills"]
                existing.skills_blob = sb
                existing.eligibility = item["eligibility"]
                existing.grad_years = item["grad_years"]
                existing.location = item["location"]
                existing.city = item["city"]
                existing.work_type = item["work_type"]
                existing.stipend_text = item["stipend_text"]
                existing.stipend_min = item["stipend_min"]
                existing.stipend_max = item["stipend_max"]
                existing.duration_text = item["duration_text"]
                existing.duration_months = item["duration_months"]
                existing.deadline = item["deadline"]
                existing.status = item["status"]
                existing.status_basis = item["status_basis"]
                existing.link_ok = item["link_ok"]
                existing.validation_status = item["validation_status"]
                existing.updated_at = now
                existing.last_seen_at = now
                count_updated += 1
            else:
                intern = Internship(
                    fingerprint=fp,
                    apply_url_key=item["application_url"],
                    source_name=item["source_name"],
                    external_id=item["external_id"],
                    source_url=item["source_url"],
                    title=item["title"],
                    company=item["company"],
                    company_website=item["company_website"],
                    description=item["description"],
                    skills=item["skills"],
                    skills_blob=sb,
                    eligibility=item["eligibility"],
                    grad_years=item["grad_years"],
                    location=item["location"],
                    city=item["city"],
                    work_type=item["work_type"],
                    stipend_text=item["stipend_text"],
                    stipend_min=item["stipend_min"],
                    stipend_max=item["stipend_max"],
                    duration_text=item["duration_text"],
                    duration_months=item["duration_months"],
                    deadline=item["deadline"],
                    application_url=item["application_url"],
                    status=item["status"],
                    status_basis=item["status_basis"],
                    link_ok=item["link_ok"],
                    validation_status=item["validation_status"],
                    collected_at=now,
                    updated_at=now,
                    last_seen_at=now,
                )
                db.add(intern)
                by_url[item["application_url"]] = intern
                by_fp[fp] = intern
                count_added += 1

        db.commit()
        total_open = db.query(Internship).filter(Internship.status.in_(["open", "closing_soon"])).count()
        print(f"Seed sync complete: added {count_added}, updated {count_updated}. Total open: {total_open}")
        return total_open
    finally:
        if close_db:
            db.close()


def seed():
    Base.metadata.create_all(engine)
    ensure_columns()
    seed_listings()


if __name__ == "__main__":
    seed()
