_ALIAS_TO_CANON: dict[str, str] = {}
for canon, aliases in SKILLS.items():
    _ALIAS_TO_CANON[canon.lower()] = canon
    for a in aliases:
        _ALIAS_TO_CANON[a.lower()] = canon

# one regex, longest alias first
_SKILL_RE = re.compile(
    r"(?<![a-z0-9+#.])("
    + "|".join(re.escape(a) for a in sorted(_ALIAS_TO_CANON, key=len, reverse=True))
    + r")(?![a-z0-9+#])",
    re.IGNORECASE,
)


def extract_skills(text: str | None) -> list[str]:
    if not text:
        return []
    found = {_ALIAS_TO_CANON[m.group(1).lower()] for m in _SKILL_RE.finditer(text) if m.group(1).lower() in _ALIAS_TO_CANON}
    return sorted(found)


def canonical_skill(name: str | None) -> str | None:
    return _ALIAS_TO_CANON.get((name or "").strip().lower())


def canonical_role(name: str | None) -> str | None:
    n = (name or "").strip().lower()
    for r in ROLES:
        if r.lower() == n:
            return r
    return None


def canonical_specialization(name: str | None) -> str | None:
    n = (name or "").strip().lower()
    for s in SPECIALIZATIONS:
        if s.lower() == n:
            return s
    return None


def skills_blob(skills: list[str]) -> str:
    return "|" + "|".join(s.lower() for s in skills) + "|" if skills else ""


def _suggest(options: list[str], q: str, limit: int) -> list[str]:
    q = (q or "").strip().lower()
    if not q:
        return options[:limit]
    starts = [o for o in options if o.lower().startswith(q)]
    contains = [o for o in options if q in o.lower() and o not in starts]
    return (starts + contains)[:limit]


def suggest_skills(q: str, limit: int = 20) -> list[str]:
    names = sorted(SKILLS)
    out = _suggest(names, q, limit)
    if len(out) < limit and q:
        c = canonical_skill(q)
        if c and c not in out:
            out.insert(0, c)
    return out[:limit]


def suggest_roles(q: str, limit: int = 20) -> list[str]:
    return _suggest(ROLES, q, limit)


def suggest_specializations(q: str, limit: int = 20) -> list[str]:
    return _suggest(SPECIALIZATIONS, q, limit)
